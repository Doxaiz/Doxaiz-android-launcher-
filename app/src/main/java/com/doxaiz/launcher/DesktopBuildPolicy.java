package com.doxaiz.launcher;

/**
 * Решение «строить рабочий стол сейчас или отложить до прихода приложений».
 *
 * <p>Зачем это отдельный класс, а не условие внутри {@code rebuildDesktop()}.
 * Условие в UI-коде нельзя проверить ничем, кроме запуска на устройстве, а
 * ошибка в нём стоит дорого: рабочий стол может остаться пустым навсегда.
 * Здесь же — чистая функция без Android, поэтому все её исходы проверяются
 * JVM-тестом {@code DesktopBuildPolicyTests}.
 *
 * <p>Найдено в §51: при холодном старте рабочий стол пересобирается дважды, и
 * первая сборка идёт до прихода списка приложений — {@code builds_no_apps=1}.
 * Она строит страницы-подсказки «Страница N, удерживайте пустую клетку»,
 * которые не попадают ни в один кадр: через сотни миллисекунд приходит
 * {@code onAppsUpdated} и строит всё заново.
 *
 * <p>Почему не «просто пропустить при пустом списке». В истории проекта уже был
 * случай, когда пустой список приложений создал и сохранил пустую страницу,
 * флаг «построено» выставился, и рабочий стол остался пустым навсегда. Поэтому
 * откладывать сборку разрешено только тогда, когда известно, что данные
 * придут: загрузка запущена и не провалилась. Если загрузка не запускалась или
 * уже завершилась неудачей, откладывать нельзя — надо показать то, что есть.
 */
public final class DesktopBuildPolicy {

    /** Что делать при вызове пересборки. */
    public enum Decision {
        /** Строить страницы: приложения есть, либо ждать больше нечего. */
        BUILD,
        /**
         * Не строить и не трогать уже построенное: приложений ещё нет, но
         * загрузка идёт и её результат придёт в {@code onAppsUpdated}.
         */
        DEFER
    }

    private DesktopBuildPolicy() {
    }

    /**
     * @param appCount            сколько приложений уже известно вызывающему коду
     * @param loadStarted         загрузка списка приложений запущена
     * @param loadFinished        загрузка завершилась (успешно или нет)
     * @param loadFailed          завершилась неудачей — данных может не быть вовсе
     *                            (на исход не влияет: завершённая загрузка, удачная
     *                            или нет, означает «ждать больше нечего»)
     * @param alreadyBuiltAnything на экране уже есть построенный рабочий стол
     * @return строить или отложить
     */
    public static Decision decide(int appCount,
                                  boolean loadStarted,
                                  boolean loadFinished,
                                  boolean loadFailed,
                                  boolean alreadyBuiltAnything) {
        // Приложения есть — строим всегда. Это единственный случай, ради
        // которого вообще нужна пересборка.
        if (appCount > 0) return Decision.BUILD;

        // Загрузка не начиналась: ждать нечего, откладывание превратилось бы в
        // вечный пустой экран.
        if (!loadStarted) return Decision.BUILD;

        // Загрузка завершилась: пустой список — это ответ, а не «ещё не
        // пришло», независимо от того, успешный он или с ошибкой. Ждать больше
        // нечего, поэтому строим подсказку, как раньше.
        //
        // Успешное завершение с нулём приложений — не выдумка: оно бывает,
        // когда все приложения скрыты пользователем. Если такой случай увести
        // в DEFER, экран останется пустым без объяснения и без надежды, что
        // что-то придёт: следующий onAppsUpdated может не случиться вовсе.
        if (loadFinished) return Decision.BUILD;

        // На экране уже что-то построено (например, пользователь вернулся на
        // рабочий стол после неудачного обновления списка). Стирать готовое
        // ради ожидания — регресс: пустой экран вместо рабочего.
        if (alreadyBuiltAnything) return Decision.BUILD;

        // Приложений нет, загрузка идёт и ещё не провалилась — откладываем.
        return Decision.DEFER;
    }
}
